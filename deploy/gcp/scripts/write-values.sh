#!/usr/bin/env bash
# Write deploy/k8s/overlays/<env>/values.env from Terraform outputs (non-secret identifiers only).
#
#   deploy/gcp/scripts/write-values.sh staging
#
# Run it after `terraform init` for that environment's backend. Review the diff, then commit.
set -euo pipefail

ENV_NAME="${1:?usage: write-values.sh <staging|production>}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUT="$ROOT/deploy/k8s/overlays/$ENV_NAME/values.env"

json="$(terraform -chdir="$ROOT/deploy/gcp/terraform" output -json values_env)"
{
  echo "# Infrastructure identifiers for $ENV_NAME - generated by deploy/gcp/scripts/write-values.sh"
  echo "# from Terraform outputs on $(date -u +%F). Non-secret by design; secrets live in Secret Manager."
  jq -r 'to_entries | sort_by(.key) | .[] | "\(.key)=\(.value)"' <<<"$json"
} > "$OUT"
echo "wrote $OUT"
